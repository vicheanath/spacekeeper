let browseToken = 0;

/** Listeners registered through Tauri's event bridge, by event name. */
const listeners = new Map<string, Set<(payload: unknown) => void>>();

function emit(event: string, payload: unknown): void {
  for (const handler of listeners.get(event) ?? []) handler(payload);
}

/** Install the stub. No-op inside Tauri, where the real bridge already exists. */
export function installDevMock(): void {
  if (typeof window === "undefined" || "__TAURI_INTERNALS__" in window) return;

  (window as unknown as Record<string, unknown>).__TAURI_INTERNALS__ = {
    // The event bridge: the mock never emits scan progress, so a scan simply
    // completes. Progress rendering is exercised by the real backend.
    transformCallback: (callback: unknown) => callback,
    invoke: async (command: string, args: Record<string, unknown> = {}) => {
      // Tauri's `listen()` routes through `invoke`, so the event bridge is
      // implemented here rather than as a normal command.
      if (command === "plugin:event|listen") {
        const event = args.event as string;
        const handler = args.handler as (payload: unknown) => void;
        const set = listeners.get(event) ?? new Set();
        set.add((payload) => handler({ event, id: 0, payload }));
        listeners.set(event, set);
        return 0;
      }

      const handler = HANDLERS[command];
      if (!handler) {
        // `plugin:event|listen` and friends arrive here; resolving keeps the
        // UI quiet rather than filling the console with unhandled rejections.
        return null;
      }
      // A small delay makes loading states visible while developing.
      await new Promise((resolve) => setTimeout(resolve, 120));
      return handler(args);
    },
  };

  // eslint-disable-next-line no-console
  console.info("[SpaceKeeper] dev mock backend installed — data on screen is fake.");
}
