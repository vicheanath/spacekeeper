function listing(path: string): DirectoryListing {
  const rows = TREE[path] ?? [];
  const total = rows.reduce((sum, [, , size]) => sum + size, 0);
  const entries: BrowseEntry[] = rows.map(([name, kind, size, protection]) => ({
    name,
    path: `${path}/${name}`,
    kind,
    // Files are known immediately; directories arrive unmeasured and are
    // filled in by the fake streaming pass below, like the real backend.
    size: kind === "file" ? size : 0,
    measured: kind === "file",
    fileCount: kind === "directory" ? Math.max(1, Math.round(size / 60_000)) : 1,
    share: total > 0 ? size / total : 0,
    lastAccessed: daysAgo(name === "old-api" ? 412 : 14),
    lastModified: daysAgo(name === "old-api" ? 412 : 14),
    protection,
    isSymlink: false,
  }));

  const segments = path.replace("/Users/you", "").split("/").filter(Boolean);
  let walked = "/Users/you";
  const breadcrumbs = [{ name: "you", path: walked }];
  for (const segment of segments) {
    walked = `${walked}/${segment}`;
    breadcrumbs.push({ name: segment, path: walked });
  }

  return {
    path,
    parent: path === "/Users/you" ? null : path.slice(0, path.lastIndexOf("/")),
    breadcrumbs,
    totalSize: total,
    entries,
    hiddenEntries: 0,
    protection:
      path === "/Users/you/Documents"
        ? { kind: "caution", reason: "your documents" }
        : { kind: "allowed" },
  };
}

