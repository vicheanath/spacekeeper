/**
 * A fake backend for running the UI in a plain browser.
 *
 * `npm run dev` without Tauri is the fastest way to work on the interface —
 * no Rust rebuild, instant HMR, and browser devtools. This installs a stub
 * `__TAURI_INTERNALS__` so `invoke()` resolves with representative data.
 *
 * It is behind `import.meta.env.DEV` at the only call site, so Vite drops the
 * whole module from production builds. It never runs inside Tauri, because
 * Tauri defines `__TAURI_INTERNALS__` itself.
 */

