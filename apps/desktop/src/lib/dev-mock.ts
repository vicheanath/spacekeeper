function daysAgo(days: number): string {
  return new Date(Date.now() - days * 86_400_000).toISOString();
}

function result(
  scanner: string,
  title: string,
  path: string,
  size: number,
  risk: ScanResult["risk"],
  category: ScanResult["category"],
  description: string,
  idleDays: number,
  score: number,
): ScanResult {
  return {
    id: `${scanner}-${path}`,
    scanner,
    title,
    description,
    path,
    size,
    kind: "directory",
    fileCount: Math.round(size / 40_000),
    category,
    risk,
    deletable: risk !== "dangerous",
    recoverable: true,
    lastAccessed: daysAgo(idleDays),
    lastModified: daysAgo(idleDays),
    score,
    confidence: 0.9,
  };
}

