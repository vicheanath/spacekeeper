//! `node_modules` directories belonging to projects you have stopped working on.
//!
//! The interesting part is not finding them — it is deciding which ones matter.
//! A `node_modules` next to a project you edited yesterday is not clutter; one
//! next to a project untouched for a year is. So the scanner dates each
//! directory by its *project*, not by the dependency files inside it, which
//! npm rewrites on every install.

use std::path::{Path, PathBuf};

use spacekeeper_core::{
    fsutil, Bytes, Category, EntryKind, Family, Result, RiskLevel, ScanContext, ScanResult,
    Scanner, ScannerMetadata,
};
use time::OffsetDateTime;

use crate::rules::display_path;
use crate::walk::{walk, Descend};

/// Finds `node_modules` directories.
#[derive(Debug, Clone, Default)]
pub struct NodeModulesScanner;

#[async_trait::async_trait]
impl Scanner for NodeModulesScanner {
    fn metadata(&self) -> ScannerMetadata {
        ScannerMetadata {
            id: "node_modules".into(),
            name: "Node modules".into(),
            description: "Dependency folders belonging to JavaScript projects".into(),
            explanation: "Libraries installed for a JavaScript project. They are listed in the project's package.json and can always be reinstalled by running `npm install` in that folder.".into(),
            family: Family::Developer,
            default_risk: RiskLevel::Safe,
            platforms: vec!["macos".into(), "linux".into(), "windows".into()],
            enabled_by_default: true,
            requires_tool: Some("node".into()),
        }
    }

    async fn scan(&self, context: &ScanContext) -> Result<Vec<ScanResult>> {
        let progress = context.progress_for("node_modules");
        let roots = context.roots.clone();
        let guard = std::sync::Arc::clone(&context.guard);
        let control = context.control.clone();
        let max_depth = context.options.max_depth;
        let min_size = context.options.min_result_size;
        let stale_days = f64::from(context.options.stale_after_days);
        let home = context.home.clone();

        let results = tokio::task::spawn_blocking(move || -> Result<Vec<ScanResult>> {
            let mut candidates: Vec<PathBuf> = Vec::new();
            walk(
                &roots,
                &guard,
                &control,
                max_depth,
                |entry| {
                    // Stop at the boundary: report the folder, never walk the
                    // hundred thousand files inside it.
                    if entry.file_name() == "node_modules" {
                        Descend::No
                    } else {
                        Descend::Yes
                    }
                },
                |entry| {
                    if entry.file_type().is_dir() && entry.file_name() == "node_modules" {
                        candidates.push(entry.path().to_path_buf());
                    }
                },
            )?;

            let now = OffsetDateTime::now_utc();
            let mut found: Vec<ScanResult> = fsutil::measure_all(&candidates, &control)
                .into_iter()
                .filter(|(_, stats)| stats.size >= min_size)
                .map(|(path, stats)| {
                    let project = path.parent().unwrap_or(&path).to_path_buf();
                    let touched = project_last_touched(&project).or(stats.last_modified);
                    let idle = touched
                        .map(|ts| ((now - ts).whole_seconds().max(0) as f64) / 86_400.0)
                        .unwrap_or(0.0);

                    // A lockfile means `npm install` reproduces exactly what
                    // is there now. Without one, reinstalling can pull newer
                    // versions and change how the project behaves — the same
                    // folder, but a materially riskier suggestion.
                    let reproducible = has_lockfile(&project);

                    let description = if !reproducible {
                        "Dependencies for a project with no lockfile. Reinstalling may pull newer versions than the ones here, so the project could behave differently afterwards.".to_string()
                    } else if idle >= stale_days {
                        format!(
                            "Dependencies for a project you last changed {} days ago. Run `npm install` in that folder to bring them back.",
                            idle.round() as i64
                        )
                    } else {
                        "Dependencies for a project you are still working on. Removing them means reinstalling before the next build.".to_string()
                    };

                    ScanResult::builder("node_modules", &path)
                        .title(display_path(&project, &home))
                        .description(description)
                        .size(stats.size)
                        .file_count(stats.files)
                        .kind(EntryKind::Directory)
                        .category(Category::PackageCache)
                        .deletable(true)
                        .recoverable(true)
                        // Date the result by the project, not by the folder.
                        .last_accessed(touched)
                        .last_modified(touched)
                        // Without a lockfile this is a Review, not a one-click
                        // Safe: the user could end up with different code.
                        .risk(if reproducible { RiskLevel::Safe } else { RiskLevel::Review })
                        // An active project is a much weaker recommendation
                        // than an abandoned one, and confidence feeds the score.
                        .confidence(match (reproducible, idle >= stale_days) {
                            (true, true) => 0.95,
                            (true, false) => 0.5,
                            (false, true) => 0.6,
                            (false, false) => 0.3,
                        })
                        .build()
                })
                .collect();

            found.sort_by(|a, b| b.size.cmp(&a.size));
            Ok(found)
        })
        .await
        .map_err(|err| spacekeeper_core::Error::Other(anyhow::anyhow!(err)))??;

        let total: Bytes = results.iter().map(|r| r.size).sum();
        progress.scanning(results.len() as u64, total, None);
        Ok(results)
    }
}

/// Whether the project pins its dependencies, so a reinstall is reproducible.
fn has_lockfile(project: &Path) -> bool {
    ["package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "npm-shrinkwrap.json"]
        .iter()
        .any(|name| project.join(name).exists())
}

/// When the project itself — not its dependencies — was last modified.
///
/// Uses the manifest and lockfiles, which change when a developer works on the
/// project and not when a tool rewrites `node_modules`.
fn project_last_touched(project: &Path) -> Option<OffsetDateTime> {
    [
        "package.json",
        "package-lock.json",
        "pnpm-lock.yaml",
        "yarn.lock",
        "src",
    ]
    .iter()
    .filter_map(|name| std::fs::metadata(project.join(name)).ok())
    .filter_map(|meta| meta.modified().ok())
    .map(OffsetDateTime::from)
    .max()
}

#[cfg(test)]
mod tests {
    use super::*;
    use spacekeeper_core::ScanOptions;
    use std::fs;

    fn context(home: &Path) -> ScanContext {
        ScanContext::new(home.to_path_buf()).with_options(ScanOptions {
            min_result_size: Bytes::ZERO,
            stale_after_days: 90,
            ..ScanOptions::default()
        })
    }

    fn write(path: &Path, bytes: usize) {
        fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
        fs::write(path, vec![b'x'; bytes]).expect("write");
    }

    fn age(path: &Path, days: u64) {
        let when = std::time::SystemTime::now() - std::time::Duration::from_secs(days * 86_400);
        let file = fs::File::options().write(true).open(path).expect("open");
        file.set_times(fs::FileTimes::new().set_accessed(when).set_modified(when))
            .expect("set times");
    }

    fn project(home: &Path, name: &str, dep_bytes: usize) -> PathBuf {
        let root = home.join("code").join(name);
        write(&root.join("package.json"), 100);
        write(&root.join("package-lock.json"), 50);
        write(&root.join("node_modules/left-pad/index.js"), dep_bytes);
        root
    }

    /// Same, but without a lockfile, so a reinstall is not reproducible.
    fn unpinned_project(home: &Path, name: &str, dep_bytes: usize) -> PathBuf {
        let root = home.join("code").join(name);
        write(&root.join("package.json"), 100);
        write(&root.join("node_modules/left-pad/index.js"), dep_bytes);
        root
    }

    #[tokio::test]
    async fn finds_node_modules_folders() {
        let home = tempfile::tempdir().expect("tempdir");
        project(home.path(), "api", 5000);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        assert_eq!(results.len(), 1);
        assert!(results[0].path.ends_with("node_modules"));
        assert_eq!(results[0].size, Bytes(5000));
        assert_eq!(results[0].risk, RiskLevel::Safe);
        assert!(results[0].deletable);
    }

    #[tokio::test]
    async fn the_title_names_the_project_not_the_folder() {
        let home = tempfile::tempdir().expect("tempdir");
        project(home.path(), "api", 5000);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        assert!(
            results[0].title.ends_with("code/api"),
            "got {}",
            results[0].title
        );
    }

    #[tokio::test]
    async fn abandoned_projects_score_higher_than_active_ones() {
        let home = tempfile::tempdir().expect("tempdir");
        let old = project(home.path(), "old", 5000);
        project(home.path(), "current", 5000);
        // Age every file the freshness check looks at: regenerating a lockfile
        // is real work on a project, so it counts as recent activity.
        age(&old.join("package.json"), 500);
        age(&old.join("package-lock.json"), 500);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        let old_result = results
            .iter()
            .find(|r| r.title.contains("old"))
            .expect("old project");
        let new_result = results
            .iter()
            .find(|r| r.title.contains("current"))
            .expect("current project");

        assert!(old_result.confidence > new_result.confidence);
        assert!(old_result.description.contains("days ago"));
        assert!(new_result.description.contains("still working on"));
    }

    #[tokio::test]
    async fn a_project_without_a_lockfile_is_never_one_click_safe() {
        let home = tempfile::tempdir().expect("tempdir");
        unpinned_project(home.path(), "unpinned", 5000);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");

        assert_eq!(
            results[0].risk,
            RiskLevel::Review,
            "reinstalling without a lockfile can change what the project runs"
        );
        assert!(results[0].description.contains("no lockfile"));
    }

    #[tokio::test]
    async fn a_pinned_project_is_safe_to_reinstall() {
        let home = tempfile::tempdir().expect("tempdir");
        project(home.path(), "pinned", 5000);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        assert_eq!(results[0].risk, RiskLevel::Safe);
    }

    #[tokio::test]
    async fn nested_node_modules_are_not_reported_separately() {
        let home = tempfile::tempdir().expect("tempdir");
        let root = project(home.path(), "api", 1000);
        write(
            &root.join("node_modules/pkg/node_modules/inner/index.js"),
            500,
        );

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        assert_eq!(
            results.len(),
            1,
            "the outer folder already accounts for the inner one"
        );
        assert_eq!(results[0].size, Bytes(1500));
    }

    #[tokio::test]
    async fn multiple_projects_are_ordered_largest_first() {
        let home = tempfile::tempdir().expect("tempdir");
        project(home.path(), "small", 100);
        project(home.path(), "big", 9000);

        let results = NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan");
        assert_eq!(results.len(), 2);
        assert!(results[0].title.contains("big"));
    }

    #[tokio::test]
    async fn a_home_without_projects_yields_nothing() {
        let home = tempfile::tempdir().expect("tempdir");
        fs::create_dir_all(home.path().join("code")).expect("mkdir");
        assert!(NodeModulesScanner
            .scan(&context(home.path()))
            .await
            .expect("scan")
            .is_empty());
    }
}
